"""Transliterate a Microkit CapDL JSON spec (`microkit ... --capdl-json`) into a Lean term.

No semantic reduction happens here: every object, in order, with its kind and every capability in
its slots (target object id, rights that matter, IRQ table). Which caps grant what is computed in
Lean (SystemCaps.lean), not here. Usage: capdl_to_lean.py SPEC.json LEAN_NAME > out.lean
"""
import json
import sys


def lean_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def b(x):
    return 'true' if x else 'false'


def cap(c):
    (k, v), = c.items()
    o = v['object']
    r = v.get('rights', {})
    if k == 'Frame':
        return f'.frame {o} {b(r.get("write"))}'
    if k == 'PageTable':
        return f'.pageTable {o}'
    if k == 'CNode':
        return f'.cnode {o}'
    if k == 'ArmIrqHandler':
        return f'.irqHandler {o}'
    if k == 'Notification':
        return f'.notification {o} {b(r.get("read"))} {b(r.get("write"))}'
    if k == 'Endpoint':
        return f'.endpoint {o} {b(r.get("grant"))}'
    if k == 'Tcb':
        return f'.tcb {o}'
    return f'.other {o}'


def obj(o):
    ob = o['object']
    if isinstance(ob, str):
        kind, body = ob, {}
    else:
        (kind, body), = ob.items()
    slots = body.get('slots', []) if isinstance(body, dict) else []
    caps = '[' + ', '.join(cap(s['cap']) for s in slots) + ']'
    if kind == 'Frame':
        p = body.get('paddr')
        k = f'.frame {"none" if p is None else f"(some {p})"} {body["size_bits"]}'
    elif kind == 'PageTable':
        k = '.pageTable'
    elif kind == 'CNode':
        k = '.cnode'
    elif kind == 'Tcb':
        k = '.tcb'
    elif kind == 'ArmIrq':
        k = '.irq'
    elif kind == 'Notification':
        k = '.ntfn'
    elif kind == 'Endpoint':
        k = '.ep'
    else:
        k = '.other'
    return f'  ⟨{lean_str(o["name"])}, {k}, {caps}⟩'


def main():
    spec = json.load(open(sys.argv[1]))
    name = sys.argv[2]
    objs = spec['objects']
    irqs = ', '.join(f'({i["irq"]}, {i["handler"]})' for i in spec['irqs'])
    print('-- GENERATED by capdl_to_lean.py from a Microkit --capdl-json spec. Do not edit.')
    print('import SystemCaps')
    print('namespace CapDL')
    # Chunks of 64 objects (a single 1,400-element literal exceeds the elaborator's recursion
    # depth); the Spec's object list is their concatenation, in order.
    chunks = [objs[i:i + 64] for i in range(0, len(objs), 64)]
    for k, ch in enumerate(chunks):
        print(f'def {name}_part{k} : List Obj := [')
        print(',\n'.join(obj(o) for o in ch))
        print(']')
    parts = ' ++ '.join(f'{name}_part{k}' for k in range(len(chunks)))
    print(f'def {name} : Spec := ⟨{parts}, [{irqs}]⟩')
    print('end CapDL')


main()
